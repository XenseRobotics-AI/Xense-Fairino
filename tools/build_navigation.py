#!/usr/bin/env python3
"""Generate reviewable Nav2 configuration from the checked runtime chassis URDF."""
import argparse
import json
from pathlib import Path
import sys
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from apps.navigation.footprint import ChassisFootprint
from apps.navigation.profile import build_profile
from apps.fairino_keyboard.control_core import DEFAULT_LINEAR, DEFAULT_ANGULAR


def build():
    return build_profile(ChassisFootprint(ROOT/'models/amr_8dof.urdf').points,
                         DEFAULT_LINEAR, DEFAULT_ANGULAR)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT/'apps/navigation/nav2.yaml'
    data = build()
    if args.check:
        if not target.is_file() or yaml.safe_load(target.read_text()) != data:
            raise SystemExit('Nav2 profile differs from URDF/default speeds; run tools/build_navigation.py')
        print('Nav2 profile matches URDF and chassis speed defaults')
    else:
        target.write_text('# Generated by tools/build_navigation.py; edit profile.py, then regenerate.\n'
                          + yaml.safe_dump(data, sort_keys=False))
        print(target)


if __name__ == '__main__':
    main()
